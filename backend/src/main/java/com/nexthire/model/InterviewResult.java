package com.nexthire.model;

import jakarta.persistence.*;
import java.time.LocalDateTime;

/**
 * InterviewResult — Stores the AI-generated evaluation result of a completed interview.
 */
@Entity
@Table(name = "interview_results")
public class InterviewResult {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "interview_id", nullable = false, unique = true)
    private Long interviewId;

    // ---------------------------------------------------------------
    // Score Breakdown (matches the analytics section on the frontend)
    // ---------------------------------------------------------------
    @Column(name = "overall_score")
    private int overallScore;           // Composite score shown in the ring

    @Column(name = "communication_score")
    private int communicationScore;     // Communication pillar

    @Column(name = "confidence_score")
    private int confidenceScore;        // Confidence pillar

    @Column(name = "technical_score")
    private int technicalScore;         // Technical Knowledge pillar

    @Column(name = "clarity_score")
    private int clarityScore;           // Clarity pillar

    @Column(name = "answer_structure_score")
    private int answerStructureScore;   // Answer Structure pillar

    // ---------------------------------------------------------------
    // Qualitative Feedback (generated by AI service)
    // ---------------------------------------------------------------
    @Column(name = "overall_feedback", columnDefinition = "TEXT")
    private String overallFeedback;     // General paragraph feedback

    @Column(name = "strengths", columnDefinition = "TEXT")
    private String strengths;           // JSON: ["Good vocabulary", "Clear structure"]

    @Column(name = "improvements", columnDefinition = "TEXT")
    private String improvements;        // JSON: ["Speak slower", "Add more examples"]

    @Column(name = "star_evaluation", columnDefinition = "TEXT")
    private String starEvaluation;      // STAR method breakdown text

    // ---------------------------------------------------------------
    // Result Label (shown as badge on frontend)
    // ---------------------------------------------------------------
    @Column(name = "readiness_label", length = 100)
    private String readinessLabel;      // "Interview Ready", "Needs Practice", "Excellent"

    @Column(name = "generated_at")
    private LocalDateTime generatedAt;

    @PrePersist
    protected void onCreate() {
        if (generatedAt == null) {
            generatedAt = LocalDateTime.now();
        }
    }

    // ---------------------------------------------------------------
    // Constructors
    // ---------------------------------------------------------------

    public InterviewResult() {}

    // ---------------------------------------------------------------
    // Getters and Setters
    // ---------------------------------------------------------------

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public Long getInterviewId() { return interviewId; }
    public void setInterviewId(Long interviewId) { this.interviewId = interviewId; }

    public int getOverallScore() { return overallScore; }
    public void setOverallScore(int overallScore) { this.overallScore = overallScore; }

    public int getCommunicationScore() { return communicationScore; }
    public void setCommunicationScore(int communicationScore) { this.communicationScore = communicationScore; }

    public int getConfidenceScore() { return confidenceScore; }
    public void setConfidenceScore(int confidenceScore) { this.confidenceScore = confidenceScore; }

    public int getTechnicalScore() { return technicalScore; }
    public void setTechnicalScore(int technicalScore) { this.technicalScore = technicalScore; }

    public int getClarityScore() { return clarityScore; }
    public void setClarityScore(int clarityScore) { this.clarityScore = clarityScore; }

    public int getAnswerStructureScore() { return answerStructureScore; }
    public void setAnswerStructureScore(int answerStructureScore) { this.answerStructureScore = answerStructureScore; }

    public String getOverallFeedback() { return overallFeedback; }
    public void setOverallFeedback(String overallFeedback) { this.overallFeedback = overallFeedback; }

    public String getStrengths() { return strengths; }
    public void setStrengths(String strengths) { this.strengths = strengths; }

    public String getImprovements() { return improvements; }
    public void setImprovements(String improvements) { this.improvements = improvements; }

    public String getStarEvaluation() { return starEvaluation; }
    public void setStarEvaluation(String starEvaluation) { this.starEvaluation = starEvaluation; }

    public String getReadinessLabel() { return readinessLabel; }
    public void setReadinessLabel(String readinessLabel) { this.readinessLabel = readinessLabel; }

    public LocalDateTime getGeneratedAt() { return generatedAt; }
    public void setGeneratedAt(LocalDateTime generatedAt) { this.generatedAt = generatedAt; }
}
